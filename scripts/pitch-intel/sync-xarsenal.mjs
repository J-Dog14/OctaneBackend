#!/usr/bin/env node
/**
 * Copies the xArsenal engine and benchmarks from the Octane app into this
 * backend, verbatim, so Pitch Intelligence grades exactly like Octane.
 *
 *   node scripts/pitch-intel/sync-xarsenal.mjs <path to the Octane repo>
 *
 * Reads <octane>/services/xArsenal/scoreArsenal.ts and writes
 * lib/pitch-intel/xarsenal/octane-engine.ts (server-only: it contains the
 * thresholds). Re-run whenever the benchmarks or scoring change in Octane.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { execSync } from "node:child_process";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const octane = process.argv[2] ? resolve(process.argv[2]) : null;
const srcFile = octane && join(octane, "services", "xArsenal", "scoreArsenal.ts");
if (!srcFile || !existsSync(srcFile)) {
  console.error("Usage: node scripts/pitch-intel/sync-xarsenal.mjs <path to the Octane repo>");
  process.exit(1);
}

let commit = "unknown";
try {
  commit = execSync("git rev-parse --short HEAD", { cwd: octane, stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
} catch {
  /* not a git checkout */
}

const lines = readFileSync(srcFile, "utf8").replace(/\r\n/g, "\n").split("\n");
const DECL =
  /^(?:export\s+)?(?:(?:async\s+)?function\s+([A-Za-z_$][\w$]*)|(?:const|let|var)\s+([A-Za-z_$][\w$]*)\b|interface\s+([A-Za-z_$][\w$]*)\b|type\s+([A-Za-z_$][\w$]*)\b)/;

const decls = new Map();
lines.forEach((line, i) => {
  const m = line.match(DECL);
  if (!m) return;
  const name = m[1] ?? m[2] ?? m[3] ?? m[4];
  if (decls.has(name)) return;
  let end = i + 1;
  while (end < lines.length && (lines[end] === "" || /^[\s})\]>]/.test(lines[end]))) end++;
  while (end > i + 1 && lines[end - 1].trim() === "") end--;
  decls.set(name, { name, start: i, body: lines.slice(i, end).join("\n").replace(/^export\s+/, "") });
});

const WANTED = [
  "SUBTYPE_DISPLAY",
  "VELOCITY_OFFSETS",
  "VELOCITY_WEIGHT_MULTIPLIERS",
  "NO_SPIN_EFF",
  "BENCHMARKS",
  "CLAMP_RANGES",
  "clamp",
  "monotoneCubicInterpolant",
  "scoreMetric",
  "metricStatus",
  "letterGrade",
  "gradeLabel",
  "arsenalDescription",
  "SUBTYPES_BY_CATEGORY",
  "InteractionBonus",
  "INTERACTION_BONUSES",
];
const missing = WANTED.filter((n) => !decls.has(n));
if (missing.length) {
  console.error(`scoreArsenal.ts no longer has: ${missing.join(", ")}. Update WANTED in this script.`);
  process.exit(1);
}

const picked = WANTED.map((n) => decls.get(n)).sort((a, b) => a.start - b.start);
const exported = WANTED.filter((n) => n !== "InteractionBonus");

const out = `/* AUTO-GENERATED by scripts/pitch-intel/sync-xarsenal.mjs. Do not edit by hand.
 * Source: Octane services/xArsenal/scoreArsenal.ts @ ${commit}
 *
 * SERVER-ONLY: contains the xArsenal benchmarks. Never import this from a
 * client component, and never copy it into a public repo.
 */
/* eslint-disable */
import {
  GradeLetter,
  type CompLevel,
  type DisplayType,
  type MetricStatus,
  type MetricThresholds,
  type PitchBenchmark,
  type PitchCategory,
  type PitchInput,
  type PitchResult,
  type PitchSubtype,
} from "./types";

${picked.map((d) => d.body).join("\n\n")}

export type { InteractionBonus };
export {
  ${exported.join(",\n  ")},
};
`;

const outDir = join(repoRoot, "lib", "pitch-intel", "xarsenal");
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "octane-engine.ts"), out);
console.log(`Wrote lib/pitch-intel/xarsenal/octane-engine.ts from Octane @ ${commit} (${picked.length} declarations)`);
