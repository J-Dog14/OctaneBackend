def log(msg=""):
    print(msg, flush=True)


def sim(a, b):
    return SequenceMatcher(None, a or "", b or "").ratio()


# ---------------------------------------------------------------- discovery
def find_session_folders(data_dir: Path):
    """Folders containing a session.xml (the data dir itself counts)."""
    out = []
    for dp, dns, fns in os.walk(data_dir, followlinks=True):
        if "session.xml" in fns:
            out.append(Path(dp))
    return sorted(out)


def resolve_data_dir(arg_session):
    if arg_session:
        return Path(arg_session)
    d = os.environ.get("ATHLETIC_SCREEN_DATA_DIR", "").strip() or DEFAULT_DATA_ROOT
    p = Path(d)
    if p.name.lower() == "output files":
        log(f"ERROR: ATHLETIC_SCREEN_DATA_DIR points at '{p}'. The Visual3D Output Files step is retired - "
            f"set Settings -> uais_data_dir_athletic_screen to the Data folder ({DEFAULT_DATA_ROOT}).")
        sys.exit(2)
    if not p.exists():
        log(f"ERROR: data folder not found: {p}")
        sys.exit(2)
    return p


# ---------------------------------------------------------------- DB helpers
def q(conn, sql, params=None):
    with conn.cursor() as cur:
        cur.execute(sql, params)
        cols = [d[0] for d in cur.description]
        return pd.DataFrame(cur.fetchall(), columns=cols)


def v2_tables_exist(conn):
    r = q(conn, "SELECT to_regclass('public.f_athletic_screen_v2_cmj') IS NOT NULL AS ok")
    return bool(r.ok.iloc[0])


def ingested_sessions(conn):
    """{(source_athlete_id, session_folder): athlete_uuid} already in v2."""
    parts = [f"SELECT DISTINCT source_athlete_id, session_folder, athlete_uuid, session_date "
             f"FROM {schema.TABLE.format(mv)}" for mv in schema.MOVEMENTS]
    df = q(conn, " UNION ".join(parts))
    return df


def athlete_row(conn, uuid):
    r = q(conn, "SELECT athlete_uuid, name, email, date_of_birth, gender FROM analytics.d_athletes "
                "WHERE athlete_uuid = %s", (uuid,))
    return r.iloc[0].to_dict() if len(r) else None


# ---------------------------------------------------------------- readiness cross-insert
READINESS_SOURCES_WE_OWN = ("athletic_screen", "athletic_screen_v2")


def readiness_row(r, mv):
    """Map a v2 CMJ/PPU trial onto the readiness table columns (old column conventions)."""
    f = lambda k: (None if r.get(k) is None or (isinstance(r.get(k), float) and not np.isfinite(r.get(k)))
                   else float(r.get(k)))
    v = f("vel_at_pp_m_s")
    return {
        "athlete_uuid": r["athlete_uuid"], "session_date": r["session_date"],
        "source_system": "athletic_screen_v2", "source_athlete_id": r.get("source_athlete_id"),
        "trial_name": r["trial_name"], "trial_id": int(r["trial_number"]),
        "age_at_collection": f("age_at_collection"), "age_group": r.get("age_group"),
        "jump_height": f("jh_in"),
        "peak_power": f("peak_power_w"), "pp_forceplate": f("peak_power_w"), "peak_power_w": f("peak_power_w"),
        "pp_w_per_kg": f("pp_w_per_kg"), "force_at_pp": f("force_at_pp_n"),
        "vel_at_pp": v * 1000.0 if v is not None else None,          # readiness/old convention: mm/s
        "peak_force": f("peak_force_n"), "peak_grf_n": f("peak_force_n"), "peak_grf_bw_ratio": f("peak_force_bw"),
        "rpd_max_w_per_s": f("rpd_max_w_per_s"), "rise_time_10_90_s": f("rise_time_10_90_s"),
        "decay_90_10_s": f("decay_90_10_s"), "fwhm_s": f("pwr_con_fwhm_s"), "auc_j": f("concentric_work_j"),
        "t_com_norm_0to1": f("pwr_con_time_com_norm"),
        "skewness": f("pwr_con_value_skew"), "kurtosis": f("pwr_con_value_kurtosis"),
        # file-start-relative timings are undefined in v2 (trials are cropped)
        "time_to_peak_s": None, "time_to_rpd_max_s": None, "work_early_pct": None, "spectral_centroid_hz": None,
        "contraction_time_s": f("contraction_time_s"), "eccentric_duration_s": f("eccentric_duration_s"),
        "concentric_duration_s": f("concentric_duration_s"), "ecc_con_duration_ratio": f("ecc_con_duration_ratio"),
        "eccentric_peak_power_w": f("eccentric_peak_power_w"), "concentric_impulse_ns": f("concentric_impulse_ns"),
        "mrsi": f("mrsi"),
        "eccentric_mean_power_w": None, "eccentric_auc_j": None, "concentric_auc_j": f("concentric_work_j"),
        "rfd_0_100ms": None,
    }


def cross_insert_readiness(conn, rows, mv):
    table = f"public.f_readiness_screen_{mv}"
    n_ins = n_upd = n_skip = 0
    with conn.cursor() as cur:
        for r in rows:
            d = readiness_row(r, mv)
            cur.execute(f"SELECT source_system FROM {table} WHERE athlete_uuid=%s AND session_date=%s AND trial_id=%s",
                        (d["athlete_uuid"], d["session_date"], d["trial_id"]))
            ex = cur.fetchone()
            if ex and ex[0] not in READINESS_SOURCES_WE_OWN:
                n_skip += 1          # a real readiness trial lives there - never overwrite it
                continue
            cols = list(d)
            if ex:
                upd = [c for c in cols if c not in ("athlete_uuid", "session_date", "trial_id")]
                cur.execute(f"UPDATE {table} SET {', '.join(f'{c}=%s' for c in upd)} "
                            f"WHERE athlete_uuid=%s AND session_date=%s AND trial_id=%s",
                            [d[c] for c in upd] + [d["athlete_uuid"], d["session_date"], d["trial_id"]])
                n_upd += 1
            else:
                cur.execute(f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({', '.join(['%s'] * len(cols))})",
                            [d[c] for c in cols])
                n_ins += 1
    return n_ins, n_upd, n_skip


# ---------------------------------------------------------------- athlete resolution
def resolve_athlete(conn, srow, selected_uuid, history, dry_run):
    """Return (athlete_uuid, how). Raises ValueError when the selected athlete clearly isn't this folder."""
    from common.athlete_manager import (get_or_create_athlete, normalize_email,
                                        normalize_name_for_matching as nn)
    from common.athlete_utils import extract_source_athlete_id
    from common.session_xml import normalize_gender

    name = srow["athlete_name"]
    names = {nn(x) for x in (name, srow.get("xml_name")) if isinstance(x, str) and x}
    if selected_uuid:
        a = athlete_row(conn, selected_uuid)
        if a is None:
            raise ValueError(f"selected ATHLETE_UUID {selected_uuid} not found")
        s = max(sim(nn(a["name"]), n) for n in names)
        hist = history[(history.source_athlete_id == srow["athlete_folder"])
                       & (history.athlete_uuid == selected_uuid)]
        if s < 0.70 and hist.empty:
            raise ValueError(f"NAME_MISMATCH_ERROR: folder '{srow['athlete_folder']}' vs selected athlete "
                             f"'{a['name']}' (similarity {s:.0%})")
        if s < 0.90 and hist.empty:
            log(f"NAME_MISMATCH_WARNING: folder '{srow['athlete_folder']}' vs selected athlete '{a['name']}' "
                f"(similarity {s:.0%}). Proceeding - verify this is correct.")
        return selected_uuid, "selected"

    prior = history[history.source_athlete_id == srow["athlete_folder"]].athlete_uuid.unique()
    if len(prior) == 1:
        return prior[0], "v2_history"
    if dry_run:
        return None, "would get_or_create (dry run)"
    email = srow.get("email")
    uuid, created = get_or_create_athlete(
        name=name, date_of_birth=srow.get("dob") or None,
        email=normalize_email(email) if isinstance(email, str) and email else None,
        gender=normalize_gender(srow.get("gender")),
        source_system="athletic_screen", source_athlete_id=extract_source_athlete_id(name))
    return uuid, ("created" if created else "matched")


def fill_profile(conn, uuid, srow):
    """Fill DOB / gender from session.xml only where d_athletes has nothing."""
    from common.athlete_manager import update_athlete_in_warehouse
    from common.session_xml import normalize_gender
    a = athlete_row(conn, uuid) or {}
    upd = {}
    if srow.get("dob") and not a.get("date_of_birth"):
        upd["date_of_birth"] = srow["dob"]
    g = normalize_gender(srow.get("gender"))
    if g and not a.get("gender"):
        upd["gender"] = g
    if upd:
        update_athlete_in_warehouse(uuid, conn=conn, **upd)
        log(f"  profile filled from session.xml: {', '.join(upd)}")


def age_fields(conn, uuid, session_date, fallback_dob):
    from common.age_utils import calculate_age_at_collection, calculate_age_group, parse_date
    a = athlete_row(conn, uuid) if conn is not None else None
    dob = (a or {}).get("date_of_birth") or fallback_dob
    if not dob:
        return None, None
    d0 = dob if hasattr(dob, "year") else parse_date(str(dob))
    d1 = datetime.strptime(str(session_date), "%Y-%m-%d").date()
    age = calculate_age_at_collection(d1, d0) if d0 else None
    if age is None or age < 0 or age > 120:
        return None, None
    return round(float(age), 2), calculate_age_group(age)


# ---------------------------------------------------------------- main
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--offline", action="store_true", help="no database access at all")
    ap.add_argument("--reprocess", action="store_true", help="re-ingest sessions already in v2")
    ap.add_argument("--session", help="ingest just this session folder")
    ap.add_argument("--since", default="2025-07-01")
    ap.add_argument("--box-height-cm", type=float, default=30.5)
    args = ap.parse_args()

    data_dir = resolve_data_dir(args.session)
    selected = os.environ.get("ATHLETE_UUID", "").strip() or None
    log(f"Athletic Screen ingest v2 (processor {PROCESSOR_VERSION})" + (" [DRY RUN]" if args.dry_run else "")
        + (" [OFFLINE]" if args.offline else ""))
    log(f"Data: {data_dir}" + (f"   Selected athlete: {selected}" if selected else ""))

    conn = None
    history = pd.DataFrame(columns=["source_athlete_id", "session_folder", "athlete_uuid", "session_date"])
    if not args.offline:
        from common.athlete_manager import get_warehouse_connection
        conn = get_warehouse_connection()
        if args.dry_run:
            conn.set_session(readonly=True)
        if not v2_tables_exist(conn):
            log("ERROR: v2 tables missing - run load_v2.py --apply once to create them.")
            sys.exit(2)
        history = ingested_sessions(conn)
        if selected and athlete_row(conn, selected) is None:
            log(f"ERROR: selected athlete {selected} not found in d_athletes")
            sys.exit(1)

    folders = find_session_folders(data_dir)
    is_upload = len(folders) == 1 and folders[0] == data_dir and data_dir.name.startswith("uais-")
    data_root = data_dir if not (len(folders) == 1 and folders[0] == data_dir) else data_dir.parent
    if not is_upload:
        folders = [f for f in folders if not TEST_RE.match(f.parent.name)]
    log(f"{len(folders)} session folder(s) found")

    done = set(zip(history.source_athlete_id, history.session_folder))
    sel_name = None
    if selected and conn is not None:
        from common.athlete_manager import normalize_name_for_matching as nn
        sel_name = nn(athlete_row(conn, selected)["name"])
        sel_folders = set(history[history.athlete_uuid == selected].source_athlete_id)

    work_dir = Path(tempfile.mkdtemp(prefix="as_v2_ingest_"))
    (work_dir / "curves").mkdir()
    sessions = []          # (srow, rows, errors, curve_key_prefix)
    skipped_done = []
    for f in folders:
        ath_folder = f.parent.name
        if selected and sel_name is not None and not is_upload:
            from common.athlete_manager import normalize_name_for_matching as nn
            nm, _ = athlete_from_folder(ath_folder)
            if ath_folder not in sel_folders and sim(nn(nm), sel_name) < 0.85:
                continue
        if (ath_folder, f.name) in done and not args.reprocess and not is_upload:
            skipped_done.append(f)
            continue
        srow, rows, errs = process_session(f, data_root, work_dir, args.box_height_cm, args.since)
        status = srow.get("status", "")
        if not status.startswith("ok"):
            if "not an Athletic Screen" not in status and "no Athletic Screen" not in status:
                log(f"  skip {f.relative_to(data_root)}: {status}")
            continue
        prefix = f"{srow['athlete_folder']}__{f.name}__"
        if is_upload:   # temp upload dir: name the session like the Data folder would
            xml_folder = f"{srow['xml_name']}_{srow.get('athlete_id') or ''}".strip("_")
            for r in rows:
                r["athlete_folder"] = xml_folder
                r["athlete_name"] = srow["xml_name"]
                r["session_folder"] = f"{srow['session_date']}_"
            srow["athlete_folder"] = xml_folder
            srow["athlete_name"] = srow["xml_name"]
        sessions.append((srow, rows, errs, prefix))
        log(f"  new: {f.relative_to(data_root) if f != data_root else f.name}  ({status})")

    if selected and not sessions and skipped_done and conn is not None:
        mine = [f for f in skipped_done if (f.parent.name in sel_folders)]
        if mine:
            from common.session_duplicate_prompt import prompt_duplicate_session
            latest = max(mine, key=lambda p: p.name)
            sd = latest.name[:10]
            log(f"No new sessions for this athlete; latest already ingested: {latest.relative_to(data_root)}")
            if not args.dry_run and prompt_duplicate_session(sd):
                srow, rows, errs = process_session(latest, data_root, work_dir, args.box_height_cm, args.since)
                if srow.get("status", "").startswith("ok"):
                    sessions.append((srow, rows, errs, f"{srow['athlete_folder']}__{latest.name}__"))

    # Metadata may be added to session.xml after its force data was ingested.
    # Refresh email through the existing folder -> UUID link without reprocessing c3d.
    if conn is not None and skipped_done:
        records = []
        missing = set(q(conn, "SELECT athlete_uuid FROM analytics.d_athletes "
                             "WHERE NULLIF(TRIM(email), '') IS NULL").athlete_uuid)
        for folder in skipped_done:
            uuids = history.loc[history.source_athlete_id == folder.parent.name, "athlete_uuid"].unique()
            if len(uuids) == 1 and uuids[0] in missing and (not selected or uuids[0] == selected):
                try:
                    meta = parse_session_xml(folder / "session.xml")
                except (ValueError, OSError, ET.ParseError) as exc:
                    log(f"  skip profile email {folder}: {type(exc).__name__}")
                    continue
                records.append(dict(athlete_uuid=uuids[0], email=meta["email"]))
        filled, review = fill_missing_emails(conn, records, dry_run=args.dry_run)
        if filled or review:
            log(f"Existing sessions: {len(filled)} missing email(s) {'would be ' if args.dry_run else ''}filled; "
                f"{len(review)} need review")
        if not args.dry_run:
            conn.commit()

    if not sessions:
        log("Nothing new to ingest.")
        if conn is not None:
            conn.close()
        return 0

    from common.athlete_matcher import update_athlete_data_flag
    from common.athlete_manager import update_athlete_age_group_from_insert
    processed_uuids, all_errors, n_rows = [], [], {mv: 0 for mv in schema.MOVEMENTS}

    # group by athlete folder + date so same-day folders merge into one session
    for srow, rows, errs, prefix in sessions:
        all_errors += [f"{e['athlete_folder']} {e['session_date']} {e['trial_name']}: {e['error']}" for e in errs]
        for r in rows:
            r["_curve"] = work_dir / "curves" / f"{prefix}{r['trial_name']}.npz"

    by_athlete = {}
    for srow, rows, errs, prefix in sessions:
        by_athlete.setdefault(srow["athlete_folder"], []).append((srow, rows))

    for ath_folder, items in by_athlete.items():
        srow0 = items[0][0]
        try:
            uuid, how = (None, "offline") if conn is None else resolve_athlete(conn, srow0, selected, history, args.dry_run)
        except ValueError as e:
            log(str(e))
            all_errors.append(f"{ath_folder}: {e}")
            continue
        log(f"\nAthlete: {srow0['athlete_name']}  ->  {uuid or '(new)'}  [{how}]")

        frames = {mv: [] for mv in schema.MOVEMENTS}
        for srow, rows in items:
            for r in rows:
                r = dict(r)
                r["athlete_uuid"] = uuid or "00000000-0000-0000-0000-000000000000"
                r["session_date"] = str(r["session_date"])
                r["source_athlete_id"] = ath_folder
                r["source_system"] = "athletic_screen_v2"
                frames[r["movement"].lower()].append(r)

        try:
            if conn is not None and uuid and not args.dry_run:
                for srow, _ in items:
                    fill_profile(conn, uuid, srow)
                filled, review = fill_missing_emails(conn, [dict(athlete_uuid=uuid, email=s.get("email")) for s, _ in items])
                if filled:
                    log("  profile email filled from session.xml")
                if review:
                    log(f"  EMAIL_REVIEW: conflicting session email for {uuid}")
            for mv in schema.MOVEMENTS:
                if not frames[mv]:
                    continue
                df = pd.DataFrame(frames[mv])
                df, merged = merge_same_day(df)
                for line in merged:
                    log(f"  merged same-day folders -> {line}")
                ages = {d: age_fields(conn if uuid else None, uuid, d, srow0.get("dob")) for d in df.session_date.unique()}
                df["age_at_collection"] = df.session_date.map(lambda d: ages[d][0])
                df["age_group"] = df.session_date.map(lambda d: ages[d][1])
                df["qc_flags"] = df.qc_flags.fillna("").map(lambda s: [x for x in str(s).split(";") if x])
                n_rows[mv] += len(df)
                flags = sorted({x for fl in df.qc_flags for x in fl})
                log(f"  {mv.upper()}: {len(df)} trials" + (f"  QC: {', '.join(flags)}" if flags else ""))
                if conn is None or args.dry_run or not uuid:
                    continue
                with conn.cursor() as cur:   # replace this session's rows so dropped trials don't linger
                    for sd, sf in set(zip(df.session_date, df.session_folder)):
                        for t in (schema.TABLE.format(mv), schema.CURVE_TABLE):
                            extra = " AND movement=%s" if t == schema.CURVE_TABLE else ""
                            cur.execute(f"DELETE FROM {t} WHERE athlete_uuid=%s AND session_date=%s AND session_folder=%s{extra}",
                                        (uuid, sd, sf) + ((mv.upper(),) if extra else ()))
                upsert(conn, schema.TABLE.format(mv), df, schema.trial_columns(mv), schema.UNIQUE_KEY)
                curves = []
                for r in df.to_dict("records"):
                    p = r["_curve"]
                    if not Path(p).exists():
                        continue
                    z = np.load(p)
                    curves.append(dict(athlete_uuid=uuid, session_date=r["session_date"], session_folder=r["session_folder"],
                                       movement=mv.upper(), trial_name=r["trial_name"], fs_hz=float(z["fs_hz"]),
                                       fz_n=[round(float(x), 2) for x in z["fz_n"]], bw_n=float(z["bw_n"]),
                                       plate_offset_n=float(z["plate_offset_n"]), first_frame=int(z["first_frame"]),
                                       takeoff_idx=int(z["takeoff_idx"]), landing_idx=int(z["landing_idx"]),
                                       contact_start_idx=int(z["contact_start_idx"]),
                                       concentric_start_idx=int(z["concentric_start_idx"]),
                                       movement_onset_idx=int(z["movement_onset_idx"]), processor_version=PROCESSOR_VERSION))
                upsert(conn, schema.CURVE_TABLE, pd.DataFrame(curves), schema.CURVE_COLS, schema.UNIQUE_KEY)
                # No readiness cross-insert any more (2026-10-28): readiness reads Readiness Screen v2 and
                # unions v_athletic_screen_* explicitly, so copying screens into f_readiness_screen_* counted
                # them twice. cross_insert_readiness() is kept only for reference.
                ag = df.age_group.dropna()
                if len(ag):
                    update_athlete_age_group_from_insert(uuid, ag.iloc[-1], conn=conn)
            if conn is not None and uuid and not args.dry_run:
                update_athlete_data_flag(conn, uuid, "athletic_screen", has_data=True)
                conn.commit()
                processed_uuids.append(uuid)
                log("  committed")
        except Exception as e:
            if conn is not None:
                conn.rollback()
            log(f"  ERROR - rolled back this athlete: {type(e).__name__}: {e}")
            all_errors.append(f"{ath_folder}: {type(e).__name__}: {e}")

    if processed_uuids and conn is not None:
        try:
            from common.duplicate_detector import check_and_merge_duplicates
            check_and_merge_duplicates(conn=conn, athlete_uuids=list(set(processed_uuids)))
        except Exception as e:
            log(f"Warning: duplicate check failed: {e}")

    log(f"\nRows {'that would be ' if args.dry_run or conn is None else ''}written: "
        + ", ".join(f"{mv.upper()} {n}" for mv, n in n_rows.items()))
    if all_errors:
        log(f"{len(all_errors)} issue(s):")
        for e in all_errors:
            log(f"  - {e}")
    if processed_uuids and conn is not None and not args.dry_run:
        # PDF report (reads the v2 tables + v2 force curves) for each athlete's latest ingested session
        try:
            import main as legacy_main   # report code lives there; it now reads v2
            latest = {}
            for uuid in set(processed_uuids):
                a = athlete_row(conn, uuid)
                dates = q(conn, " UNION ".join(f"SELECT max(session_date) AS d FROM {schema.TABLE.format(mv)} "
                                               f"WHERE athlete_uuid = %s" for mv in schema.MOVEMENTS),
                          tuple([uuid] * len(schema.MOVEMENTS))).d.dropna()
                if a and len(dates):
                    latest[uuid] = (a["name"], str(max(dates))[:10])
            if latest:
                log(f"Generating PDF report(s) for {len(latest)} athlete(s)...")
                legacy_main.run_report_generation(latest, None)
        except Exception as e:
            log(f"Warning: report generation failed: {type(e).__name__}: {e}")
    if conn is not None:
        conn.close()
    log("Successful run and upload." if not all_errors else "Run finished with issues (see above).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
