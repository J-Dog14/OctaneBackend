#!/usr/bin/env python3
"""
Athletic Screen ingest (v2) - what runs when you hit Ingest for the athletic-screen runner.

Replaces the legacy flow (Visual3D -> Output Files txt -> main.py -> f_athletic_screen_*).
Reads c3d + session.xml directly and writes ONLY the v2 tables:
    public.f_athletic_screen_v2_{cmj,dj,ppu,slv}, public.f_athletic_screen_v2_force_curve
(The readiness baseline cross-insert into f_readiness_screen_cmj/ppu was removed 2026-10-28.)

Where the data comes from (ATHLETIC_SCREEN_DATA_DIR, i.e. Settings -> uais_data_dir_athletic_screen):
  * the Data root (D:\\Athletic Screen 2.0\\Data): every Athletic Screen session folder that is not in
    the v2 tables yet is ingested ("auto-find"). With an athlete selected (ATHLETE_UUID) only that
    athlete's folders are considered; if none are new you're asked whether to re-ingest the latest one.
  * a single session folder, or an upload/agent temp dir with c3d + session.xml at its root.

Rules (same as the rebuild): Athletic Screen sessions only (session.xml), on/after --since
(2025-07-01), every trial on FP3 (otherwise the session is skipped), Test*/Sample Report folders
skipped, two athletic-screen folders for one athlete on one date are merged into one session.

Steps per session, in one transaction:
  1. process c3d -> metrics + force curves (kinetics.py, QC flags)
  2. resolve the athlete: selected UUID (name guard) | athlete already in v2 under this folder |
     get_or_create_athlete (prints NEW_ATHLETE / MISSING_DOB signals for the UI)
  3. fill missing DOB / email / gender from session.xml
  4. age_at_collection + age_group (d_athletes DOB), update d_athletes.age_group
  5. replace this session's v2 rows (delete + insert) and curves
  6. (removed 2026-10-28) readiness baseline cross-insert
  7. has_athletic_screen_data flag
After all sessions: duplicate-athlete check.

Usage (the backend runs it with ATHLETIC_SCREEN_DATA_DIR / ATHLETE_UUID set):
    python v2/ingest.py [--dry-run] [--reprocess] [--session PATH] [--since YYYY-MM-DD] [--offline]
    --dry-run   process + resolve athletes (read-only DB), print what would be written
    --offline   no database at all (processing check only)
Report flags (--report-only / --comparison) are handed to the legacy report code for now.
"""
